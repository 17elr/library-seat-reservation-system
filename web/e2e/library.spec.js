import { test, expect } from '@playwright/test'
import { mkdir } from 'node:fs/promises'
const shots = '../docs/images/vue'
async function login(page, account = '20260001', password = 'Student123!') {
  await page.goto('/login')
  await page.getByLabel('账号', { exact: true }).fill(account)
  await page.getByLabel('密码', { exact: true }).fill(password)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.locator('.sidebar')).toBeVisible()
}
async function bookPage(page) {
  await login(page)
  await page.getByRole('link', { name: '预约座位', exact: true }).click()
  await page.locator('.el-select__wrapper').first().click()
  await page.getByRole('option').nth(1).click()
  await expect(page.locator('.seat').first()).toBeVisible()
}
test('login, images, keyboard seats, booking and cancellation', async ({ page }) => {
  await mkdir(shots, { recursive: true })
  await page.goto('/login')
  await expect(page.locator('.login-photo')).toBeVisible()
  await page.screenshot({ path: shots + '/login.png', fullPage: true })
  await bookPage(page)
  const seat = page.locator('.seat:not(.unavailable)').first()
  await seat.focus()
  await page.keyboard.press('Enter')
  await expect(seat).toHaveAttribute('aria-pressed', 'true')
  await page.screenshot({ path: shots + '/booking.png', fullPage: true })
  await page.getByRole('button', { name: '确认预约', exact: true }).click()
  await page.getByRole('button', { name: '提交预约', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '预约详情' })).toBeVisible()
  page.on('dialog', (d) => d.accept())
  await page.getByRole('button', { name: '取消预约', exact: true }).click()
  await expect(page.getByRole('dialog').getByText('已取消', { exact: true })).toBeVisible()
  await page.screenshot({ path: shots + '/detail.png', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
})
test('old response cannot replace new room selection', async ({ page }) => {
  await bookPage(page)
  await page.route('**/api/rooms/*/seats?*', async (route) => {
    if (route.request().url().includes('/rooms/2/'))
      await new Promise((resolve) => setTimeout(resolve, 500))
    await route.continue().catch(() => {})
  })
  const rooms = page.locator('.room-tab')
  await rooms.nth(1).click()
  await rooms.nth(2).click()
  await expect(page.locator('.seat').first()).toContainText('C')
  await page.waitForTimeout(700)
  await expect(page.locator('.seat').first()).toContainText('C')
})
test('network retry reuses requestKey and preserves selection', async ({ page }) => {
  await bookPage(page)
  const bodies = []
  await page.route('**/api/reservations', async (route) => {
    bodies.push(route.request().postDataJSON())
    if (bodies.length === 1) await route.abort('connectionfailed')
    else
      await route.fulfill({
        status: 409,
        contentType: 'application/json',
        body: JSON.stringify({ message: '座位冲突，请重新选择' })
      })
  })
  await page.locator('.seat:not(.unavailable)').first().click()
  await page.getByRole('button', { name: '确认预约', exact: true }).click()
  await page.getByRole('button', { name: '提交预约', exact: true }).click()
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('网络连接中断')
  await page.getByRole('button', { name: '提交预约', exact: true }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  expect(bodies).toHaveLength(2)
  expect(bodies[0]).toEqual(bodies[1])
  await expect(page.locator('.selection-panel .selection-number')).toContainText('请选择座位')
})
