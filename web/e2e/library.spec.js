test('admin forms keep field errors and input on failure', async ({ page }) => {
  await login(page, 'admin', 'Admin123!')
  await page.screenshot({ path: shots + '/admin.png', fullPage: true })
  await page.getByRole('link', { name: '阅览室管理', exact: true }).click()
  await page.reload()
  await expect(page.getByRole('heading', { name: '阅览室管理', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '新增', exact: true }).click()
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('请检查以下字段')
  await expect(page.getByRole('alert')).toBeFocused()
  await page.getByLabel('编号', { exact: false }).fill('TESTROOM')
  await page.getByLabel('名称', { exact: false }).fill('回归阅览室')
  await page.getByLabel('楼层', { exact: false }).fill('4F')
  await page.getByLabel('操作原因', { exact: false }).fill('浏览器失败回归')
  page.on('dialog', (d) => d.accept())
  await page.route('**/api/admin/rooms', (r) =>
    r.request().method() === 'POST'
      ? r.fulfill({
          status: 503,
          contentType: 'application/json',
          body: '{"message":"数据库暂不可用"}'
        })
      : r.continue()
  )
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('数据库暂不可用')
  await expect(page.getByLabel('名称', { exact: false })).toHaveValue('回归阅览室')
  await page.screenshot({ path: shots + '/admin-errors.png', fullPage: true })
})

